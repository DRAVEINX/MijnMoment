import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
const files=['index.html','styles.css','app.js','manifest.webmanifest','sw.js','capacitor.config.json','package.json','assets/mijnmoment-icon.svg'];
for(const f of files)assert.ok(existsSync(f),'Ontbrekend bestand: '+f);
const html=readFileSync('index.html','utf8'),js=readFileSync('app.js','utf8'),css=readFileSync('styles.css','utf8'),sw=readFileSync('sw.js','utf8');
const manifest=JSON.parse(readFileSync('manifest.webmanifest','utf8'));
const capacitor=JSON.parse(readFileSync('capacitor.config.json','utf8'));
const pkg=JSON.parse(readFileSync('package.json','utf8'));
assert.equal(manifest.name,'MijnMoment');
assert.equal(manifest.display,'standalone');
assert.equal(capacitor.appId,'nl.draveinx.mijnmoment');
assert.equal(capacitor.webDir,'dist');
assert.ok(pkg.dependencies['@capacitor/preferences'],'Android-opslag ontbreekt');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
assert.equal(ids.length,new Set(ids).size,'Dubbele HTML-id');
for(const m of js.matchAll(/\$\('#([a-zA-Z0-9_-]+)'\)/g))assert.ok(ids.includes(m[1]),'Ontbrekend HTML-element: '+m[1]);
for(const id of ['task-list','task-status','week-days','week-search-input','appointment-list','diary','export-data','import-file'])assert.ok(ids.includes(id),'Belangrijk onderdeel ontbreekt: '+id);
for(const feature of ['function renderTasks()','function renderWeek()','function persist()','function showScreen(','nativeStorage.set({key,value})','nativeStorage.get({key})','incoming.tasks','incoming.appointments'])assert.ok(js.includes(feature),'Appfunctie ontbreekt: '+feature);
assert.ok(html.includes('aria-live="polite"'),'Toegankelijke meldingen ontbreken');
assert.ok(css.includes('[hidden]{display:none!important}'),'Verborgen schermen moeten verborgen blijven');
assert.ok(sw.includes('self.skipWaiting()')&&sw.includes('self.clients.claim()')&&sw.includes('caches.match(request,'),'Offline cache ontbreekt');
assert.ok(!/(?<!\$)\$\([^)]*\)\.forEach\s*\(/.test(js),'Een enkel DOM-element heeft geen forEach; gebruik $$ voor lijsten');
assert.equal(js.split('$$'+'(\'input[name="week-filter"]\').forEach').length-1,3,'Weekfilters moeten bij starten, wijzigen en import allemaal werken');
console.log('MijnMoment basiscontroles geslaagd.');
